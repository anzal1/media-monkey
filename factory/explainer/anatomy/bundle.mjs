/*
 * bundle.mjs: turn the vendored Anatomy kit into one classic script.
 *
 * The scene page is opened from file:// and loads plain <script src> tags, so
 * ES modules are not an option there (Chrome blocks module imports from file
 * URLs). This strips the import/export keywords from iso-kit.mjs and
 * lathe.mjs, wraps each in a function scope and publishes them as
 * window.ANATOMY = { k, G }, the same names the Anatomy examples use.
 *
 *   node factory/explainer/anatomy/bundle.mjs          writes anatomy.js
 *   node factory/explainer/anatomy/bundle.mjs --check  fails if it is stale
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, 'anatomy.js');

function unexport(file) {
  const src = fs.readFileSync(path.join(HERE, file), 'utf8')
    .replace(/^\/\/ Vendored.*\n\/\/ MIT License.*\n/, '')
    .replace(/^import .*\n/gm, '');
  const names = [...src.matchAll(/^export\s+(?:const|function|let)\s+([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
  return { body: src.replace(/^export\s+/gm, ''), names };
}

const kit = unexport('iso-kit.mjs');
const lathe = unexport('lathe.mjs');
const text = `/* GENERATED by factory/explainer/anatomy/bundle.mjs from iso-kit.mjs and lathe.mjs. Do not edit.
 * Anatomy kit by wheresryan22 (https://github.com/wheresryan22/anatomy), MIT License, see LICENSE. */
(function (root) {
  'use strict';
  const k = (function () {
${kit.body}
    return { ${kit.names.join(', ')} };
  })();
  const G = (function () {
    const { cameraOf, iso, pathOf } = k;
${lathe.body}
    return { ${lathe.names.join(', ')} };
  })();
  root.ANATOMY = { k, G };
})(typeof window !== 'undefined' ? window : globalThis);
`;

if (process.argv.includes('--check')) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (now !== text) { console.error('anatomy.js is stale: run node factory/explainer/anatomy/bundle.mjs'); process.exit(1); }
  console.log('anatomy.js is up to date');
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${kit.names.length} kit + ${lathe.names.length} lathe exports)`);
}
